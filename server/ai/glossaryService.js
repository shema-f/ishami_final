/**
 * @param {string} query
 */
export function findTerm(query) {
  if (!query) return null;
  const q = String(query).toLowerCase().trim();
  if (!q) return null;
  if (GLOSSARY[q]) return GLOSSARY[q];
  for (const key of Object.keys(GLOSSARY)) {
    const entry = GLOSSARY[key];
    if (
      key.toLowerCase().includes(q) ||
      (entry?.en || '').toLowerCase().includes(q) ||
      (entry?.rw || '').toLowerCase().includes(q)
    ) {
      return { key, ...entry };
    }
  }
  return null;
}

/**
 * @param {string} query
 * @param {number} [limit]
 */
export function searchGlossary(query, limit = 10) {
  if (!query) return [];
  const q = String(query).toLowerCase().trim();
  if (!q) return [];
  const results = [];
  for (const key of Object.keys(GLOSSARY)) {
    const entry = GLOSSARY[key];
    const score =
      (key.toLowerCase() === q ? 100 : 0) +
      ((entry?.en || '').toLowerCase() === q ? 90 : 0) +
      ((entry?.rw || '').toLowerCase() === q ? 90 : 0) +
      (key.toLowerCase().includes(q) ? 20 : 0) +
      ((entry?.en || '').toLowerCase().includes(q) ? 15 : 0) +
      ((entry?.rw || '').toLowerCase().includes(q) ? 15 : 0);
    if (score > 0) results.push({ key, ...entry, _score: score });
  }
  return results
    .sort((a, b) => b._score - a._score)
    .slice(0, limit)
    .map(({ _score, ...rest }) => rest);
}

export function getRandomTerms(count = 5) {
  const keys = Object.keys(GLOSSARY);
  const picked = [];
  while (picked.length < count && picked.length < keys.length) {
    const k = keys[Math.floor(Math.random() * keys.length)];
    if (!picked.includes(k)) picked.push(k);
  }
  return picked.map(k => ({ key: k, ...GLOSSARY[k] }));
}

export function getAllTerms() {
  return GLOSSARY;
}

export function getTermCount() {
  return Object.keys(GLOSSARY).length;
}
